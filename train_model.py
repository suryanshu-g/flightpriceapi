# 5. ROUTE & AGENCY STATS  (computed on train only — the key replacement for distance)
#
#  Why this works:
#    Real booking engines look up historical prices for each city-pair.
#    We replicate that by computing per-route price stats from training data.
#    This gives the model a strong price signal WITHOUT using internal distance/time.
# =============================================================================

