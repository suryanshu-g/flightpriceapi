def predict_price(
    from_city:   str,
    to_city:     str,
    flight_type: str,   # "economic" | "premium" | "firstClass"
    agency:      str,
    date:        str,   # "YYYY-MM-DD"
    age:         int   = 35,
    gender:      str   = "none",
) -> dict:
    """
    Predict flight price from inputs a booking website collects.

    Example
    -------
    predict_price(
        from_city="Recife (PE)",
        to_city="Florianopolis (SC)",
        flight_type="firstClass",
        agency="FlyingDrops",
        date="2024-06-15",
        age=34,
        gender="male",
    )
    """
    # Date
    d           = pd.to_datetime(date)
    month       = d.month
    dow         = d.dayofweek
    is_weekend  = int(dow in [5, 6])
    quarter     = d.quarter

    # Flight class
    if flight_type not in CLASS_MAP:
        raise ValueError(f"flight_type must be one of {list(CLASS_MAP)}")
    fc_ord = CLASS_MAP[flight_type]

    # Route stats
    route = f"{from_city} → {to_city}"
    rs    = route_stats[route_stats["route"] == route]
    if len(rs):
        r = rs.iloc[0]
        rmp, rmdp, rmin, rmax, rcnt, rrng = (
            r.route_mean_price, r.route_median_price,
            r.route_min_price,  r.route_max_price,
            r.route_count,      r.route_price_range,
        )
    else:
        rmp, rmdp = GLOBAL_ROUTE["route_mean_price"], GLOBAL_ROUTE["route_median_price"]
        rmin, rmax = GLOBAL_ROUTE["route_min_price"], GLOBAL_ROUTE["route_max_price"]
        rcnt, rrng = GLOBAL_ROUTE["route_count"],     GLOBAL_ROUTE["route_price_range"]

    # Agency stats
    ag  = agency_stats[agency_stats["agency"] == agency]
    amp = ag.iloc[0]["agency_mean_price"] if len(ag) else GLOBAL_AGENCY["agency_mean_price"]

    # Label encode
    def safe_enc(col, val):
        le = LE[col]
        return int(le.transform([val])[0]) if val in le.classes_ else 0

    row = pd.DataFrame([{
        "flightClass_ord":   fc_ord,
        "from_enc":          safe_enc("from",   from_city),
        "to_enc":            safe_enc("to",     to_city),
        "agency_enc":        safe_enc("agency", agency),
        "age":               age,
        "gender_enc":        safe_enc("gender", gender),
        "month":             month,
        "day_of_week":       dow,
        "is_weekend":        is_weekend,
        "quarter":           quarter,
        "route_mean_price":  rmp,
        "route_median_price":rmdp,
        "route_min_price":   rmin,
        "route_max_price":   rmax,
        "route_count":       rcnt,
        "route_price_range": rrng,
        "agency_mean_price": amp,
    }])[FEATURES].astype(float)

    if best_scaled:
        row = scaler.transform(row)

    price = float(tuned_model.predict(row)[0])
    return {
        "predicted_price": round(price, 2),
        "currency":        "BRL",
        "route":           route,
        "flight_type":     flight_type,
        "model":           best_name,
        "test_r2":         test_m["R2"],
    }

